        > CREATE SCHEMA
        > CREATE TABLES
        > IMPORT DATA DIRECTLY FROM PARQUET FILES IN AMAZON S3 ON AWS: https://docs.exasol.com/db/latest/loading_data/load_data_parquet.htm
        > MAKE SURE YOUR COMMUNITY EDITION IS CONNECTED TO THE INTERNET AND YOUR FIREWALL DOES NOT BLOCK TRAFFIC TO AMAZON S3

